def _guide(path):
    return [g for g in GUIDES if g[0] == path][0]

def _page(g, lead, blocks, cta, related):
    return page(g[2], g[3], g[0], article(g[0], g[1], lead, blocks, cta, related),
                extra_head=article_ld(g[2], g[3], g[0]) + breadcrumb_ld(g[1], g[0]), og_type="article")

def _tbl(head, rows):
    th = "".join(f'<th scope="col">{h}</th>' for h in head)
    body = "".join("<tr>" + f'<th scope="row">{r[0]}</th>' + "".join(f"<td>{c}</td>" for c in r[1:]) + "</tr>" for r in rows)
    return f'<div class="table-wrap"><table class="tbl"><thead><tr>{th}</tr></thead><tbody>{body}</tbody></table></div>'

